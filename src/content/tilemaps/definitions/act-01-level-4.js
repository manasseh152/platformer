const GRID_COLS = 45;
const GRID_ROWS = 70;
const BUILD_COLS = GRID_COLS * 2;
const BUILD_ROWS = GRID_ROWS * 2;

function createTerrainRows() {
  const rows = Array.from({ length: BUILD_ROWS }, () => Array.from({ length: BUILD_COLS }, () => null));

  function fillRect(x, y, w, h, kind = K.STONE) {
    for (let row = y; row < y + h; row += 1) {
      for (let col = x; col < x + w; col += 1) {
        if (row >= 0 && row < BUILD_ROWS && col >= 0 && col < BUILD_COLS) rows[row][col] = kind;
      }
    }
  }

  function stone(x, y, w, h = 2) {
    fillRect(x, y, w, h, K.STONE);
  }

  function grass(x, y, w, depth = 2) {
    fillRect(x, y, w, 1, K.GRASS);
    if (depth > 1) fillRect(x, y + 1, w, depth - 1, K.DIRT);
  }

  // High stone vault around the spawn and finish chamber.
  stone(42, 0, 16, 2);
  stone(36, 2, 22, 2);
  stone(34, 4, 4, 6);
  stone(54, 4, 6, 10);
  stone(40, 12, 16, 2);
  stone(58, 14, 24, 2);
  stone(78, 16, 4, 10);
  stone(58, 26, 22, 2);
  stone(26, 36, 38, 4);
  stone(4, 40, 22, 2);
  stone(0, 42, 3, 28);
  stone(44, 40, 4, 8);
  stone(60, 40, 8, 4);

  // Left-side descent, matching the rough stair/shaft shape from the editor draft.
  stone(0, 70, 24, 4);
  stone(0, 74, 36, 2);
  stone(0, 76, 12, 2);
  stone(0, 78, 8, 2);
  stone(0, 80, 6, 2);
  stone(0, 82, 2, 10);
  stone(8, 84, 4, 8);
  stone(20, 84, 2, 18);
  stone(32, 86, 4, 6);
  stone(38, 90, 8, 6);
  stone(46, 96, 4, 4);
  stone(52, 100, 4, 6);
  stone(62, 104, 4, 10);
  stone(16, 112, 12, 4);
  stone(42, 112, 24, 2);
  stone(56, 118, 8, 6);
  stone(4, 122, 4, 12);
  stone(16, 122, 4, 12);
  stone(40, 122, 4, 8);
  stone(60, 122, 4, 8);
  stone(0, 138, 32, 2);

  // Middle broken climb with dash-sized gaps.
  const middleStones = [
    [72, 62, 4, 6], [62, 64, 2, 6], [64, 66, 4, 4], [61, 72, 10, 4],
    [44, 96, 8, 2], [48, 98, 8, 2], [50, 104, 4, 2], [56, 108, 4, 2],
    [60, 116, 8, 2], [56, 126, 8, 2], [52, 130, 8, 2], [48, 134, 14, 2],
    [28, 118, 14, 2], [28, 124, 4, 12], [30, 136, 6, 2],
    [10, 132, 18, 2], [6, 136, 16, 2]
  ];
  for (const [x, y, w, h] of middleStones) stone(x, y, w, h);

  // Right-side grass constellation from the draft's lower half.
  const grassPatches = [
    [50, 50, 4, 2], [41, 116, 12, 2], [55, 116, 16, 2], [82, 116, 6, 2],
    [56, 124, 10, 2], [66, 124, 8, 2], [78, 124, 10, 2], [84, 128, 5, 2],
    [40, 132, 8, 2], [48, 132, 10, 2], [60, 132, 10, 2], [69, 132, 10, 2], [80, 132, 6, 2],
    [39, 138, 10, 2], [50, 138, 10, 2], [63, 138, 8, 2], [76, 138, 10, 2], [84, 138, 5, 2]
  ];
  for (const [x, y, w, h] of grassPatches) grass(x, y, w, h);

  // Sparse one-tile grass motes in the open right half create the same airy editor-authored rhythm.
  for (let y = 82; y < 138; y += 4) {
    const x = 78 + ((y * 7) % 40);
    grass(x, y, 2, 1);
    if (y % 8 === 0) grass(Math.min(BUILD_COLS - 4, x + 30), y + 2, 2, 1);
  }

  // Bottom-left rubble and dirt mound.
  stone(0, 130, 20, 2);
  stone(0, 134, 10, 2);
  fillRect(6, 128, 8, 8, K.DIRT);
  fillRect(12, 134, 14, 4, K.DIRT);
  stone(32, 136, 30, 2);
  grass(64, 128, 12, 2);

  return rows;
}

